function validateAtlasShape(width, height) {
  if (FONT_ATLAS_ROWS.length !== height) {
    throw new Error(`Bitmap font atlas has ${FONT_ATLAS_ROWS.length} rows; expected ${height}.`);
  }

  for (let y = 0; y < FONT_ATLAS_ROWS.length; y += 1) {
    const row = FONT_ATLAS_ROWS[y];
    if (row.length !== width) {
      throw new Error(`Bitmap font atlas row ${y} has ${row.length} columns; expected ${width}.`);
    }
    if (/[^.#]/.test(row)) {
      throw new Error(`Bitmap font atlas row ${y} contains unsupported characters.`);
    }
  }
}

export function createMiniTextCharsetCanvas() {
  const width = GLYPH_COLUMNS * CELL_WIDTH;
  const height = GLYPH_ROWS * CELL_HEIGHT;
  validateAtlasShape(width, height);

  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;

  const ctx = canvas.getContext('2d', { alpha: true });
  if (!ctx) {
    throw new Error('Failed to create mini bitmap font canvas context.');
  }

  ctx.imageSmoothingEnabled = false;
  ctx.fillStyle = '#fff';

  for (let y = 0; y < height; y += 1) {
    const row = FONT_ATLAS_ROWS[y];
    for (let x = 0; x < width; x += 1) {
      if (row[x] === '#') {
        ctx.fillRect(x, y, 1, 1);
      }
    }
  }

  return canvas;
}

export const miniTextFontMetrics = Object.freeze({
  columns: GLYPH_COLUMNS,
  rows: GLYPH_ROWS,
  cellWidth: CELL_WIDTH,
  cellHeight: CELL_HEIGHT,
  glyphCount: GLYPH_COLUMNS * GLYPH_ROWS,
});
